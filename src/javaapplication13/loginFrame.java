    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:5050/mydatabase",
                    "root",
                    "");
            String query = "SELECT * FROM `userdetails` WHERE username = ? AND password = ?";
            PreparedStatement statement = con.prepareStatement(query);

            statement.setString(1, jTextField2.getText());
            if (jPasswordField1.getText().isEmpty()) {
                statement.setString(2, textFieldPass.getText());
            } else {
                statement.setString(2, jPasswordField1.getText());

            }
            ResultSet res = statement.executeQuery();

            if (res.next()) {

                String status = res.getString("status");
                System.out.print(status);
                if (status.equals("employee")) {
                    dashboardEmployee dashFrame = new dashboardEmployee(res.getString("username"));
                    this.dispose();
                    dashFrame.setVisible(true);
                } else {
                    dashboardAdmin dashAdmin = new dashboardAdmin(res.getString("username"));
                    this.dispose();
                    dashAdmin.setVisible(true);
                }

            } else {
                JOptionPane.showMessageDialog(this, "can't log you in");
            }

            String historyQuery = "INSERT INTO `loginhistory`(`id`, `username`) VALUES (?,?)";
            PreparedStatement historyStatement = con.prepareStatement(historyQuery);
            historyStatement.setInt(1, res.getInt("id"));
            historyStatement.setString(2, res.getString("username"));
            historyStatement.execute();

        } catch (Exception e) {
            e.printStackTrace();

        }
    }//GEN-LAST:event_jButton1ActionPerformed


