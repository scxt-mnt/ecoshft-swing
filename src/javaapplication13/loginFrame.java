    public void passwordFocused() {
        if (jPasswordField1.getPassword().length == 0) {
            passwordLabel.setVisible(false);
            passwordLabel1.setVisible(true);
        } else {
            passwordLabel.setVisible(true);
            passwordLabel1.setVisible(false);
        }
    }

    public void usernameFocused() {
        if (jTextField2.getText().length() == 0) {
            usernameLabel.setVisible(true);
            usernameLabel1.setVisible(false);
        } else {
            usernameLabel.setVisible(false);
            usernameLabel1.setVisible(true);
        }

    }

    public void addListenerToFocus(JTextComponent textField) {
        textField.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                passwordFocused();
                usernameFocused();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                passwordFocused();
                usernameFocused();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                passwordFocused();
                usernameFocused();
            }
        });

    }

